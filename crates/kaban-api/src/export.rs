//! Export renderers (core-spec F9a, F9b, S1, S4, N5, §7; core-plan C5.2, C5.3 as amended by
//! `reviews/m5-prep.md` M5-3, M5-12, M5-16, M5-17; engine-plan E1.6, OWN-46). This module holds
//! the per-ontology `.kaban/<ontology>/INDEX.md` digest renderer (W1, M5-12) and the managed
//! marker block of `kaban export` (C5.2): [`render_export`], [`write_marker_block`] and the
//! orchestration [`export`].
//!
//! ```text
//!   export(api, { format, write, ontologies })
//!     | registry.export_blocks()          kinds with export.marker, shipped-file order,
//!     |                                   filtered by the --ontology selection (OWN-46)
//!     | briefing(ws, DIGEST_CAP)          the accepted governing records
//!     | git.head(config.repo_root)        the sha line, only inside git
//!     | render_export(records, blocks, format, sha)   deterministic bytes, (created_at, id) order
//!     | gate_document(block)              M5-3, R5-7: overlapping windows; any hit withholds
//!     | write_marker_block(path, block)   Created | Updated | Unchanged, or printed
//!     v
//!   ExportReport::Rendered { format, records, block } | ::Written { outcome, path, records }
//! ```
//!
//! The block sections and the digest sections come from the loaded ontologies (EN-F4): one
//! section per kind with `export.marker: true` (the block) or `export.digest: true` (the
//! digest of that kind's ontology), headed `export.heading`, entries linked to the record file
//! under `.kaban/<ontology>/<serialize.dir>/`. With only the shipped ontologies loaded the
//! sections are `Decisions` and `Conventions`, as before.
//!
//! The digest is kaban-owned and rewritten by `kaban sync`: it carries **no commit sha and no
//! timestamp**, so a commit that changes no record leaves it byte-identical (C5.3 slice,
//! N5). The caller hands over the accepted records (`briefing(ws, 10_000)`) and gates the
//! rendered text (`gate_response_text`) before a byte reaches the repository (M5-3); the
//! renderers write stored strings as they are.
//!
//! **The export block (F9a, M5-17).** `agents-md` and `claude-md` carry one instruction line
//! ([`INSTRUCTION_LINE`]) before the body; `markdown` omits it. The first inner line is
//! `<!-- generated by kaban export at <sha> -->` when the process runs inside a git
//! repository (M5-12), so "twice => identical" holds at one HEAD. The block is gated as one
//! document on the way out (M5-3): a reject hit withholds it, and a redact hit withholds it too
//! (masked bytes are never written; `kaban rescan` re-gates the records). The user file is
//! written atomically (temp file beside it, rename) and only when its bytes change; text
//! outside the markers is byte-preserved (CRLF, trailing-newline state), and the block takes
//! the line ending of the line holding the start marker (§7: a malformed pair is refused).

use crate::api::KabanApi;
use crate::error::ApiError;
use crate::ontology::BlockSpec;
use kaban_core::{AuditOp, Node, StoreError};
use serde::{Deserialize, Serialize};
use std::fmt::Write as _;
use std::io::Read as _;
use std::path::{Path, PathBuf};
use thiserror::Error;

/// The start marker of the managed block (core-spec F9a, core-plan C5.2).
pub const BLOCK_START: &str = "<!-- kaban:start -->";
/// The end marker of the managed block.
pub const BLOCK_END: &str = "<!-- kaban:end -->";
/// The instruction line of the `agents-md` and `claude-md` formats (M5-17).
pub const INSTRUCTION_LINE: &str =
    "Read `.kaban/adr/INDEX.md` at session start; call `why` before editing governed paths";
/// The fixed note of a withheld export after a redact hit (M5-3): the masked bytes are not
/// written; `kaban rescan` re-gates the records at `rev + 1`, after which the export renders
/// the stored (masked) text and passes.
pub const REDACT_WITHHELD_NOTE: &str = "the rendered block hit a redact rule; the export was \
     withheld rather than written masked; run `kaban rescan`, then export again";
/// Largest existing target `export --write` reads for splicing (R5-10; `[default]`: an
/// `AGENTS.md` is kilobytes). The size comes from metadata before any byte is read; a larger
/// target is refused with [`ExportError::TargetTooLarge`] and left exactly as it was.
pub const MAX_TARGET_BYTES: u64 = 8 * 1024 * 1024;

/// The block formats (core-spec F9a; M5-17).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum ExportFormat {
    /// A block for `AGENTS.md`: the instruction line, then the body.
    AgentsMd,
    /// A block for `CLAUDE.md`: the same bytes as `agents-md`.
    ClaudeMd,
    /// The body without the instruction line.
    Markdown,
}

impl ExportFormat {
    /// The CLI spelling (`agents-md`, `claude-md`, `markdown`).
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::AgentsMd => "agents-md",
            Self::ClaudeMd => "claude-md",
            Self::Markdown => "markdown",
        }
    }
}

/// What [`write_marker_block`] did to the file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum WriteOutcome {
    /// The file did not exist and was created with the block only.
    Created,
    /// The block was replaced (or appended to a file without markers).
    Updated,
    /// The file already held exactly these bytes; nothing was written.
    Unchanged,
}

/// Why an export was withheld (M5-3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WithheldCause {
    /// A reject rule hit the rendered block.
    Reject,
    /// A redact rule hit: masked bytes are never written (`kaban rescan` re-gates).
    Redact,
}

/// Why `export` could not finish. Messages carry kaban's own vocabulary, marker counts, step
/// names, I/O classes and rule ids only, never a path or a value from a file (S1, S3).
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum ExportError {
    /// The file does not hold exactly one start marker followed by one end marker (an end
    /// before the start counts as malformed too). Nothing was written.
    #[error(
        "the marker block is malformed: {starts} start and {ends} end marker(s); expected one `{BLOCK_START}` followed by one `{BLOCK_END}`"
    )]
    MalformedMarkers {
        /// Lines equal to the start marker.
        starts: usize,
        /// Lines equal to the end marker.
        ends: usize,
    },
    /// The existing target is larger than [`MAX_TARGET_BYTES`] (R5-10): it was not read and
    /// nothing was written.
    #[error("the target file is larger than the export target cap; nothing was written")]
    TargetTooLarge,
    /// The target could not be read, created, written or renamed.
    #[error("{what} failed ({kind:?})")]
    Io {
        /// Which step (`reading the target file`, `writing the temp file`, ...).
        what: &'static str,
        /// The I/O error class.
        kind: std::io::ErrorKind,
    },
    /// The rendered block hit the denylist on the way out (M5-3): nothing was written.
    #[error("the export was withheld: {}", match cause {
        WithheldCause::Reject => "a reject rule hit the rendered block",
        WithheldCause::Redact => REDACT_WITHHELD_NOTE,
    })]
    Withheld {
        /// Which class of rule hit.
        cause: WithheldCause,
        /// The rule ids of a reject hit (empty for a redact hit).
        rules: Vec<String>,
    },
    /// `--ontology` named an ontology that is not loaded (fixed class, exit 2; the name is
    /// caller data and is not echoed).
    #[error("ontology_unknown: --ontology names an ontology that is not loaded")]
    OntologyUnknown,
    /// The service refused (a policy or request failure other than the gate's verdict).
    #[error(transparent)]
    Api(ApiError),
    /// The store failed.
    #[error(transparent)]
    Store(StoreError),
}

/// Which ontologies an `export` or a digest run covers (OWN-46: `--ontology
/// <name>[,<name>...]|all`, default `all`). `kaban sync` always serializes every ontology;
/// only the digest generation and `export` honour the selection.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum OntologySelection {
    /// Every loaded ontology.
    #[default]
    All,
    /// The named ontologies only (every name must be loaded).
    Named(Vec<String>),
}

impl OntologySelection {
    /// The selection of a CLI list: empty (or the word `all`) selects everything.
    #[must_use]
    pub fn from_names(names: Vec<String>) -> Self {
        if names.is_empty() || names.iter().any(|n| n == "all") {
            Self::All
        } else {
            Self::Named(names)
        }
    }

    /// Whether `ontology` is selected.
    #[must_use]
    pub fn selects(&self, ontology: &str) -> bool {
        match self {
            Self::All => true,
            Self::Named(names) => names.iter().any(|n| n == ontology),
        }
    }

    /// The first selected name that is not among `loaded`, if any (the `ontology_unknown`
    /// check; the name itself is caller data and stays with the caller).
    #[must_use]
    pub fn unknown_among<'a>(&'a self, loaded: &[String]) -> Option<&'a str> {
        match self {
            Self::All => None,
            Self::Named(names) => names
                .iter()
                .find(|n| !loaded.iter().any(|l| l == *n))
                .map(String::as_str),
        }
    }
}

impl From<ApiError> for ExportError {
    fn from(e: ApiError) -> Self {
        match e {
            ApiError::Store(s) => Self::Store(s),
            other => Self::Api(other),
        }
    }
}

impl From<StoreError> for ExportError {
    fn from(e: StoreError) -> Self {
        Self::Store(e)
    }
}

/// The seam speaks `ApiError` (`seam::run_tool`): a withheld export is `Rejected` under the
/// field `export` (exit 2; a redact hit carries the rule id `redact` so the fixed text names
/// no value), a malformed block or an unusable path is a request error (exit 4), a store
/// failure keeps its own code (exit 5).
impl From<ExportError> for ApiError {
    fn from(e: ExportError) -> Self {
        match e {
            ExportError::Withheld { cause, rules } => Self::Rejected {
                field: "export".into(),
                rules: match cause {
                    WithheldCause::Reject => rules,
                    WithheldCause::Redact => vec!["redact".into()],
                },
            },
            ExportError::OntologyUnknown => Self::Rejected {
                field: "ontology".into(),
                rules: vec!["ontology_unknown".into()],
            },
            ExportError::Api(a) => a,
            ExportError::Store(s) => Self::Store(s),
            other => Self::Invalid(other.to_string()),
        }
    }
}

/// The request of one `export` run (M5-16: `Export { format, write }`; E1.6 `ontologies`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExportOpts {
    /// The block format.
    pub format: ExportFormat,
    /// The user file to splice the block into; `None` prints the block.
    #[serde(default)]
    pub write: Option<PathBuf>,
    /// The ontologies whose kinds the block renders (`--ontology`); empty selects all.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub ontologies: Vec<String>,
}

/// What one `export` run produced (M5-17): the block itself without `--write`, the write
/// outcome with it. Untagged: the key set tells the two apart.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum ExportReport {
    /// `--write` absent: `{"format", "records", "block"}` (the block is gated text).
    Rendered {
        /// The format rendered.
        format: ExportFormat,
        /// Records in the block (Decisions plus Conventions).
        records: usize,
        /// The complete block, markers included, `\n` line endings.
        block: String,
    },
    /// `--write <path>` given: `{"outcome", "path", "records"}`.
    Written {
        /// What happened to the file.
        outcome: WriteOutcome,
        /// The path as given.
        path: String,
        /// Records in the block (Decisions plus Conventions).
        records: usize,
    },
}

/// Render the accepted records into the managed block, gate it as one string (M5-3) and
/// print or write it.
///
/// # Errors
/// [`ExportError`]: a withheld block (a reject or redact hit; nothing written), a malformed
/// marker pair, an unusable target path, a store or service failure.
pub fn export(api: &KabanApi, opts: &ExportOpts) -> Result<ExportReport, ExportError> {
    let ws = api.config.workspace.as_str();
    let selection = OntologySelection::from_names(opts.ontologies.clone());
    let blocks = selected_blocks(api, &selection, |b| b.marker)?;
    let records = api.store.briefing(ws, &block_kinds(&blocks), DIGEST_CAP)?;
    // the sha line only inside git (M5-12): the repository the process runs in, as `accept`
    // stamps `accepted_commit`; a slow or absent git leaves the line out, never an error
    let sha = api
        .config
        .repo_root
        .as_deref()
        .and_then(|root| api.git.head(root));
    let block = render_export(&records, &blocks, opts.format, sha.as_deref());
    gate_block(api, &block)?;
    let records = records
        .iter()
        .filter(|n| blocks.iter().any(|b| b.kind == n.kind))
        .count();
    match &opts.write {
        None => Ok(ExportReport::Rendered {
            format: opts.format,
            records,
            block,
        }),
        Some(path) => Ok(ExportReport::Written {
            outcome: write_marker_block(path, &block)?,
            path: path.display().to_string(),
            records,
        }),
    }
}

/// The gate on the way out (M5-3, S1 "export output"): the whole block as one document. A
/// reject hit withholds the export (audited by the gate); a redact hit withholds it too,
/// because masked bytes in the user file would silently differ from the stored record
/// (`kaban rescan` re-gates the record; the next export then renders the masked text).
fn gate_block(api: &KabanApi, block: &str) -> Result<(), ExportError> {
    match gate_document(api, "export", "export", block)? {
        DocumentVerdict::Clean => Ok(()),
        DocumentVerdict::Redact => {
            tracing::warn!("the export was withheld: a redact rule hit; run `kaban rescan`");
            Err(ExportError::Withheld {
                cause: WithheldCause::Redact,
                rules: Vec::new(),
            })
        }
        DocumentVerdict::Reject(rules) => {
            tracing::warn!("the export was withheld: a reject rule hit");
            Err(ExportError::Withheld {
                cause: WithheldCause::Reject,
                rules,
            })
        }
    }
}

/// What the output gate says about one generated document.
#[derive(Debug)]
pub(crate) enum DocumentVerdict {
    /// No rule hit: the bytes may be written as they are.
    Clean,
    /// A redact rule hit somewhere in the document (masked bytes are never written).
    Redact,
    /// A reject rule hit: the rule ids (audited under `tool`/`field`).
    Reject(Vec<String>),
}

/// The output gate of every document kaban generates (record files, tombstones, the digest,
/// the export block; M5-3, R5-7): the rendered text is scanned in overlapping windows of
/// `max_field_chars` with a half-window stride, exactly as the raw import gate does, so a
/// document is never withheld for its length alone while a phrase that straddles a window
/// boundary is still seen whole. Withhold-on-hit semantics are the caller's: a reject hit is
/// audited here (fail-closed: an unwritable audit chain is an error) under `tool`/`field`.
///
/// # Errors
/// `ApiError::Rejected { rules: [audit-unavailable] }` when the rejection cannot be recorded.
pub(crate) fn gate_document(
    api: &KabanApi,
    tool: &str,
    field: &str,
    text: &str,
) -> Result<DocumentVerdict, ApiError> {
    let v = {
        let pol = api.pol();
        pol.scan_windows(text, pol.file.defaults.max_field_chars)
    };
    if v.rejected {
        let mut ctx = api.write_ctx(None);
        let entry = api.entry_for(
            &ctx,
            AuditOp::Reject,
            tool,
            field,
            text,
            v.reject_rules.clone(),
        );
        ctx.audit.push(entry);
        api.flush_audit(&mut ctx)?;
        return Ok(DocumentVerdict::Reject(v.reject_rules));
    }
    if v.hits.is_empty() {
        Ok(DocumentVerdict::Clean)
    } else {
        Ok(DocumentVerdict::Redact)
    }
}

/// The registry's export blocks that pass `keep` and belong to a selected ontology, in
/// shipped-file order; `OntologyUnknown` when the selection names an unloaded ontology.
pub(crate) fn selected_blocks(
    api: &KabanApi,
    selection: &OntologySelection,
    keep: impl Fn(&BlockSpec) -> bool,
) -> Result<Vec<BlockSpec>, ExportError> {
    let loaded: Vec<String> = api.registry().list().into_iter().map(|o| o.ns).collect();
    if selection.unknown_among(&loaded).is_some() {
        return Err(ExportError::OntologyUnknown);
    }
    Ok(api
        .registry()
        .export_blocks()
        .into_iter()
        .filter(|b| keep(b) && selection.selects(&b.ontology))
        .collect())
}

/// The stored kind names of `blocks` (what the briefing read is asked for).
pub(crate) fn block_kinds(blocks: &[BlockSpec]) -> Vec<&str> {
    blocks.iter().map(|b| b.kind.as_str()).collect()
}

/// The section heading of a block: `export.heading`, else the stored kind name.
fn heading_of(block: &BlockSpec) -> &str {
    block.heading.as_deref().unwrap_or(&block.kind)
}

/// Render the managed block (markers included, `\n` line endings, one trailing newline):
/// the start marker, `<!-- generated by kaban export at <sha> -->` when `generated_at_commit`
/// is given, the [`INSTRUCTION_LINE`] for `agents-md` and `claude-md`, then one `## <heading>`
/// section per block in `blocks` (the registry's marker kinds in shipped-file order; the
/// shipped ontologies: `## Decisions`, `## Conventions`) with each accepted record once in
/// `(created_at, id)` order (the title with its id, `scope`, `rationale`), then the end
/// marker. Kinds in `records` without a block are skipped. Two renders of the same input are
/// byte-identical.
#[must_use]
pub fn render_export(
    records: &[Node],
    blocks: &[BlockSpec],
    format: ExportFormat,
    generated_at_commit: Option<&str>,
) -> String {
    let mut out = format!("{BLOCK_START}\n");
    if let Some(sha) = generated_at_commit {
        let _ = writeln!(out, "<!-- generated by kaban export at {sha} -->");
    }
    if matches!(format, ExportFormat::AgentsMd | ExportFormat::ClaudeMd) {
        out.push_str(INSTRUCTION_LINE);
        out.push('\n');
    }
    for spec in blocks {
        let mut block: Vec<&Node> = records.iter().filter(|n| n.kind == spec.kind).collect();
        block.sort_by(|a, b| (&a.created_at, &a.id).cmp(&(&b.created_at, &b.id)));
        let _ = write!(out, "\n## {}\n\n", heading_of(spec));
        if block.is_empty() {
            out.push_str("(none)\n");
        }
        for n in block {
            export_entry(&mut out, n, spec);
        }
    }
    out.push_str(BLOCK_END);
    out.push('\n');
    out
}

/// One block entry (M5-17): the title with the id linked to its record file under
/// `.kaban/<ontology>/<dir>/` (the bare id for a kind without a file), then `scope` and
/// `rationale` when present. `String` writes cannot fail.
fn export_entry(out: &mut String, n: &Node, spec: &BlockSpec) {
    match &spec.dir {
        Some(dir) => {
            let _ = writeln!(
                out,
                "- **{}** ([{id}](.kaban/{ontology}/{dir}/{id}.md))",
                title_of(n),
                id = n.id,
                ontology = spec.ontology
            );
        }
        None => {
            let _ = writeln!(out, "- **{}** ({id})", title_of(n), id = n.id);
        }
    }
    if !n.path_scope.is_empty() {
        let scope: Vec<String> = n.path_scope.iter().map(|p| format!("`{p}`")).collect();
        let _ = writeln!(out, "  - scope: {}", scope.join(", "));
    }
    if let Some(rationale) = folded_rationale(n) {
        let _ = writeln!(out, "  - rationale: {rationale}");
    }
}

/// The entry title: the summary, else the first non-blank text line, else `(untitled)`.
fn title_of(n: &Node) -> &str {
    n.summary
        .as_deref()
        .filter(|s| !s.trim().is_empty())
        .or_else(|| n.text.lines().find(|l| !l.trim().is_empty()))
        .unwrap_or("(untitled)")
}

/// `props.rationale` folded onto one line (so the entry stays a list item), when present and
/// not blank.
fn folded_rationale(n: &Node) -> Option<String> {
    let rationale = n.props.get("rationale").and_then(|v| v.as_str())?;
    let folded = rationale.split_whitespace().collect::<Vec<_>>().join(" ");
    (!folded.is_empty()).then_some(folded)
}

/// Splice `block` (a complete block as [`render_export`] returns it: the start marker line
/// first, the end marker line last) into the file at `path`: a missing file is created with
/// the block only; a file without markers gets the block appended; a file with exactly one
/// start marker followed by one end marker has that region replaced. Bytes outside the block
/// are preserved verbatim (CRLF, trailing-newline state); the block takes the line ending of
/// the line holding the start marker, `\n` otherwise. Unchanged bytes are not written (the
/// mtime does not move); a write is a temp file beside the target, then a rename.
///
/// The target's size is taken from metadata before any byte is read (R5-10): a target above
/// [`MAX_TARGET_BYTES`], or one that is not a regular file, is refused untouched.
///
/// # Errors
/// [`ExportError::MalformedMarkers`] for any other marker arrangement (nothing written);
/// [`ExportError::TargetTooLarge`] for a target above the cap (nothing read or written);
/// [`ExportError::Io`] when the target cannot be read, created, written or renamed.
pub fn write_marker_block(path: &Path, block: &str) -> Result<WriteOutcome, ExportError> {
    let io = |what: &'static str| {
        move |e: std::io::Error| ExportError::Io {
            what,
            kind: e.kind(),
        }
    };
    let file = match std::fs::File::open(path) {
        Ok(file) => file,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            write_atomic(path, block.as_bytes(), None)?;
            return Ok(WriteOutcome::Created);
        }
        Err(e) => return Err(io("reading the target file")(e)),
    };
    // the size of the opened file, so a target that grows between the check and the read is
    // still bounded by the `take` below
    let meta = file.metadata().map_err(io("reading the target file"))?;
    if meta.len() > MAX_TARGET_BYTES {
        return Err(ExportError::TargetTooLarge);
    }
    if !meta.is_file() {
        return Err(ExportError::Io {
            what: "reading the target file",
            kind: std::io::ErrorKind::InvalidInput,
        });
    }
    let mut current = Vec::with_capacity(usize::try_from(meta.len()).unwrap_or(0));
    std::io::Read::take(file, MAX_TARGET_BYTES + 1)
        .read_to_end(&mut current)
        .map_err(io("reading the target file"))?;
    if u64::try_from(current.len()).unwrap_or(u64::MAX) > MAX_TARGET_BYTES {
        return Err(ExportError::TargetTooLarge);
    }
    let next = splice(&current, block)?;
    if next == current {
        return Ok(WriteOutcome::Unchanged);
    }
    let mode = std::fs::metadata(path).ok().map(|m| m.permissions());
    write_atomic(path, &next, mode)?;
    Ok(WriteOutcome::Updated)
}

/// One line of the current file: where it starts, where its content ends (before the line
/// terminator) and whether it ends with CRLF.
struct Line {
    start: usize,
    content_end: usize,
    crlf: bool,
}

/// The bytes of `current` with `block` spliced in (see [`write_marker_block`]).
fn splice(current: &[u8], block: &str) -> Result<Vec<u8>, ExportError> {
    let mut starts: Vec<Line> = Vec::new();
    let mut ends: Vec<Line> = Vec::new();
    let mut pos = 0usize;
    while pos < current.len() {
        let rel_end = current[pos..]
            .iter()
            .position(|b| *b == b'\n')
            .map_or(current.len(), |i| pos + i);
        let crlf = rel_end > pos && current[rel_end - 1] == b'\r';
        let content_end = if crlf { rel_end - 1 } else { rel_end };
        let content = current[pos..content_end].trim_ascii();
        let line = Line {
            start: pos,
            content_end,
            crlf,
        };
        if content == BLOCK_START.as_bytes() {
            starts.push(line);
        } else if content == BLOCK_END.as_bytes() {
            ends.push(line);
        }
        pos = rel_end.saturating_add(1);
    }
    match (starts.as_slice(), ends.as_slice()) {
        ([], []) => {
            // no block yet: append, separated from a last line without its newline
            let mut next = current.to_vec();
            if !next.is_empty() && !next.ends_with(b"\n") {
                next.push(b'\n');
            }
            next.extend_from_slice(block.as_bytes());
            Ok(next)
        }
        ([start], [end]) if start.start < end.start => {
            let eol: &[u8] = if start.crlf { b"\r\n" } else { b"\n" };
            let mut next = current[..start.start].to_vec();
            let body = block.strip_suffix('\n').unwrap_or(block);
            for (i, line) in body.split('\n').enumerate() {
                if i > 0 {
                    next.extend_from_slice(eol);
                }
                next.extend_from_slice(line.as_bytes());
            }
            next.extend_from_slice(&current[end.content_end..]);
            Ok(next)
        }
        (starts, ends) => Err(ExportError::MalformedMarkers {
            starts: starts.len(),
            ends: ends.len(),
        }),
    }
}

/// Write `bytes` to `path` atomically: a temp file beside it (the target's permissions when it
/// exists, 0644 otherwise), then a rename. The target's directory must exist: a user file's
/// parents are never created.
fn write_atomic(
    path: &Path,
    bytes: &[u8],
    mode: Option<std::fs::Permissions>,
) -> Result<(), ExportError> {
    use std::io::Write as _;
    use std::os::unix::fs::OpenOptionsExt as _;
    let dir = match path.parent() {
        Some(dir) if !dir.as_os_str().is_empty() => dir,
        _ => Path::new("."),
    };
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let tmp: PathBuf = dir.join(format!(".{name}.kaban-tmp-{}", std::process::id()));
    let io = |what: &'static str| {
        move |e: std::io::Error| ExportError::Io {
            what,
            kind: e.kind(),
        }
    };
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o644)
        .open(&tmp)
        .map_err(io("creating the temp file"))?;
    let written = f
        .write_all(bytes)
        .and_then(|()| match mode {
            Some(perm) => f.set_permissions(perm),
            None => Ok(()),
        })
        .and_then(|()| f.sync_all())
        .map_err(io("writing the temp file"));
    drop(f);
    if let Err(e) = written {
        let _ = std::fs::remove_file(&tmp);
        return Err(e);
    }
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        ExportError::Io {
            what: "renaming the temp file",
            kind: e.kind(),
        }
    })
}

/// First line of the digest: a fixed marker, so a reader (and the C5.5 smoke) can tell the
/// file is generated.
pub const DIGEST_HEADER: &str =
    "<!-- generated by kaban sync from the accepted Decisions and Conventions; do not edit -->";

/// The number of records the digest caller asks the briefing for (M5-12, recorded cap).
pub const DIGEST_CAP: usize = 10_000;

/// Render one ontology's `.kaban/<ontology>/INDEX.md` digest from the accepted records: the
/// fixed header, then one `## <heading>` section per block in `blocks` (that ontology's kinds
/// with `export.digest: true`, shipped-file order; the shipped `adr`: `## Decisions`,
/// `## Conventions`), each record once, ordered `(created_at, id)` inside its section. Entry
/// shape (M5-12): the summary (else the first text line) with the id linked to its record
/// file relative to the digest (`<dir>/<id>.md`), then `scope`, `accepted at <commit>` when
/// known and `rationale` (`props.rationale`) when present. Kinds in `records` without a block
/// are skipped. Two renders of the same input are byte-identical, and the shipped `adr`
/// digest is byte-identical to the pre-engine `.kaban/DECISIONS.md` (EN-F4 golden promise).
#[must_use]
pub fn render_digest(records: &[Node], blocks: &[BlockSpec]) -> String {
    let mut out = format!("{DIGEST_HEADER}\n# Decisions and conventions\n");
    for spec in blocks {
        let mut block: Vec<&Node> = records.iter().filter(|n| n.kind == spec.kind).collect();
        block.sort_by(|a, b| (&a.created_at, &a.id).cmp(&(&b.created_at, &b.id)));
        let _ = write!(out, "\n## {}\n\n", heading_of(spec));
        if block.is_empty() {
            out.push_str("(none)\n");
        }
        for n in block {
            digest_entry(&mut out, n, spec);
        }
    }
    out
}

/// One digest entry (M5-12). `String` writes cannot fail, so the `write!` results are dropped.
fn digest_entry(out: &mut String, n: &Node, spec: &BlockSpec) {
    match &spec.dir {
        Some(dir) => {
            let _ = writeln!(
                out,
                "- **{}** ([{id}]({dir}/{id}.md))",
                title_of(n),
                id = n.id
            );
        }
        None => {
            let _ = writeln!(out, "- **{}** ({id})", title_of(n), id = n.id);
        }
    }
    if !n.path_scope.is_empty() {
        let scope: Vec<String> = n.path_scope.iter().map(|p| format!("`{p}`")).collect();
        let _ = writeln!(out, "  - scope: {}", scope.join(", "));
    }
    if let Some(commit) = &n.accepted_commit {
        let _ = writeln!(out, "  - accepted at {commit}");
    }
    if let Some(rationale) = folded_rationale(n) {
        let _ = writeln!(out, "  - rationale: {rationale}");
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)] // test code: failures are the assertion
mod tests {
    use super::*;
    use crate::ontology::OntologyRegistry;
    use kaban_core::{Governance, Lifecycle, StoreScope};
    use serde_json::json;

    fn record(kind: &str, n: u8, created_at: &str, summary: Option<&str>) -> Node {
        Node {
            id: format!("01a17a03-5cbc-7000-8000-0000000000{n:02}"),
            kind: kind.into(),
            text: format!("{kind} number {n}\n\nmore text"),
            summary: summary.map(str::to_owned),
            tags: vec![],
            confidence: None,
            importance: Some(f64::from(n) / 10.0),
            lifecycle: Lifecycle::Active,
            governance: Governance::Accepted,
            store_scope: StoreScope::Project,
            path_scope: vec!["src/**".into(), "docs".into()],
            rev: 1,
            serialized_rev: None,
            dup_key: None,
            created_at: created_at.into(),
            updated_at: created_at.into(),
            valid_from: None,
            valid_to: None,
            session_id: None,
            agent_id: None,
            workspace_id: "ws".into(),
            repo: None,
            commit_sha: None,
            accepted_commit: n
                .is_multiple_of(2)
                .then(|| "89abcdef0123456789abcdef0123456789abcdef".into()),
            props: json!({"rationale": format!("because {n}")}),
            content_hash: String::new(),
            policy_version: "pv".into(),
        }
    }

    /// The shipped `adr` digest blocks (what `registry.export_blocks()` yields for `adr`
    /// with `digest: true`), built by hand so the renderer is tested without a registry.
    fn adr_blocks() -> Vec<BlockSpec> {
        OntologyRegistry::new(None)
            .unwrap()
            .export_blocks()
            .into_iter()
            .filter(|b| b.digest)
            .collect()
    }

    fn blocks(digest: &str) -> Vec<String> {
        digest
            .split("\n## ")
            .skip(1)
            .map(|b| format!("## {b}"))
            .collect()
    }

    #[test]
    fn the_digest_is_byte_identical_across_renders_and_an_added_record_changes_one_block() {
        // the briefing hands records over by importance; the digest orders by (created_at, id)
        let records = vec![
            record(
                "Decision",
                3,
                "2026-10-26T12:27:44Z",
                Some("Third decision"),
            ),
            record("Convention", 4, "2026-10-26T12:24:12Z", None),
            record(
                "Decision",
                1,
                "2026-10-26T12:24:12Z",
                Some("First decision"),
            ),
            record("Decision", 2, "2026-10-26T12:24:12Z", None),
            record("Fact", 9, "2026-10-26T12:22:26Z", Some("not in the digest")),
        ];
        let first = render_digest(&records, &adr_blocks());
        let second = render_digest(&records, &adr_blocks());
        assert_eq!(first, second, "N5: no timestamp, no sha");
        assert!(first.starts_with(DIGEST_HEADER), "{first}");
        assert!(!first.contains("not in the digest"));
        assert!(
            !first.contains("2026-10-26"),
            "no timestamps in the digest: {first}"
        );
        // (created_at, id) order inside the Decisions block
        let d1 = first.find("First decision").unwrap();
        let d2 = first.find("Decision number 2").unwrap();
        let d3 = first.find("Third decision").unwrap();
        assert!(d1 < d2 && d2 < d3, "{first}");
        // the entry shape
        assert!(
            first.contains(
                "- **First decision** ([01a17a03-5cbc-7000-8000-000000000001](decisions/01a17a03-5cbc-7000-8000-000000000001.md))"
            ),
            "{first}"
        );
        assert!(first.contains("  - scope: `src/**`, `docs`"), "{first}");
        assert!(
            first.contains("  - accepted at 89abcdef0123456789abcdef0123456789abcdef"),
            "{first}"
        );
        assert!(first.contains("  - rationale: because 1"), "{first}");
        assert!(
            first.contains("(conventions/01a17a03-5cbc-7000-8000-000000000004.md)"),
            "{first}"
        );
        assert!(
            first.ends_with('\n') && !first.ends_with("\n\n"),
            "{first:?}"
        );

        // an added Convention changes exactly one block
        let mut more = records.clone();
        more.push(record(
            "Convention",
            5,
            "2026-10-26T12:25:58Z",
            Some("Fifth"),
        ));
        let third = render_digest(&more, &adr_blocks());
        let (a, b) = (blocks(&first), blocks(&third));
        assert_eq!(a.len(), 2, "{first}");
        assert_eq!(b.len(), 2, "{third}");
        let changed: Vec<usize> = (0..2).filter(|i| a[*i] != b[*i]).collect();
        assert_eq!(
            changed,
            vec![1],
            "only the Conventions block moved:\n{first}\n---\n{third}"
        );

        // empty input still renders both blocks
        let empty = render_digest(&[], &adr_blocks());
        assert_eq!(blocks(&empty).len(), 2, "{empty}");
        assert_eq!(render_digest(&[], &adr_blocks()), empty);
    }
}
